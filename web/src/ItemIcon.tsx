export type ItemIconName = keyof typeof ITEM_ICONS;
export const isItemIcon = (name: unknown): name is ItemIconName =>
  typeof name === 'string' && Object.hasOwn(ITEM_ICONS, name);

/** An item's icon; items without one show a box. */
export default function ItemIcon({ name }: { name?: string | null }) {
  const [width, height, , , paths] = (isItemIcon(name) ? ITEM_ICONS[name] : faBox).icon;
  return (
    <svg
      className="app-icon item-icon"
      viewBox={`0 0 ${width} ${height}`}
      aria-hidden="true"
      focusable="false"
    >
      {(Array.isArray(paths) ? paths : [paths]).map((path, index) => (
        <path d={path} key={index} />
      ))}
    </svg>
  );
}
